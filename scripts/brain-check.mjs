// Validates brain/memories/corrections.json (dependency-free). `--render` regenerates deploy-pitfalls.md.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const file = path.join(root, "brain/memories/corrections.json");
const CATS = ["BUG", "DEPLOY", "ARCH", "I18N_RTL", "DATA", "AI", "ANDROID", "PROCESS"];
const errors = [];
const err = (m) => errors.push(m);

let data;
try { data = JSON.parse(fs.readFileSync(file, "utf8")); } catch (e) { console.error("corrections.json unreadable:", e.message); process.exit(1); }
if (data.version !== 1 || !Array.isArray(data.entries)) err("expected { version: 1, entries: [] }");
if (!data || typeof data !== "object") { console.error("corrections.json root must be an object"); process.exit(1); }
const entries = Array.isArray(data.entries) ? data.entries : [];
if (entries.length > 300) err(`${entries.length} entries (>300): consolidate and move superseded ones to brain/memories/archive/YYYY.json`);

const gate = fs.readFileSync(path.join(root, "scripts/gate.sh"), "utf8");
const seen = new Set();
for (const e of entries) {
  if (!e || typeof e !== "object") { err("entry is not an object"); continue; }
  const id = e.id || "(no id)";
  if (!/^L-\d{4}$/.test(id)) err(`${id}: bad id`);
  if (seen.has(id)) err(`${id}: duplicate id`); seen.add(id);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date || "") || new Date(e.date).toISOString().slice(0, 10) !== e.date) err(`${id}: bad date`);
  if (!CATS.includes(e.category)) err(`${id}: bad category`);
  for (const k of ["symptom", "rootCause", "fix", "rule"]) if (!e[k] || typeof e[k] !== "string") err(`${id}: missing ${k}`);
  if (!["agent", "owner"].includes(e.source)) err(`${id}: bad source`);
  if (!Array.isArray(e.tags) || e.tags.some((t) => typeof t !== "string")) err(`${id}: tags must be an array`);
  const g = e.guard;
  if (!g || !["test", "grep", "script"].includes(g.type) || !g.ref) { err(`${id}: missing/invalid guard`); continue; }
  if (g.type === "grep") {
    const m = /^gate\.sh:([a-z0-9-]+)$/.exec(g.ref);
    if (!m || !new RegExp(`^echo "== ${m[1]}[ :]`, "m").test(gate)) err(`${id}: grep guard not registered in gate.sh (need gate.sh:<name>): ${g.ref}`);
  } else {
    const rel = g.ref.split(":")[0];
    const abs = path.resolve(root, rel);
    if (!abs.startsWith(root + path.sep) || !fs.existsSync(abs)) err(`${id}: guard ${g.type} file not found inside repo: ${g.ref}`);
  }
}

if (process.argv.includes("--render") && !errors.length) {
  const d = entries.filter((e) => e.category === "DEPLOY");
  const md = ["# Deploy pitfalls", "", "_Generated by `node scripts/brain-check.mjs --render` from `corrections.json`. Do not edit._", "",
    ...d.map((e) => `- [ ] **${e.id}** ${e.rule} _(guard: ${e.guard.ref})_`), ""].join("\n");
  fs.writeFileSync(path.join(root, "brain/memories/deploy-pitfalls.md"), md);
}
if (errors.length) { console.error(errors.map((m) => "  - " + m).join("\n")); process.exit(1); }
console.log(`brain-check: ${entries.length} entries valid`);
